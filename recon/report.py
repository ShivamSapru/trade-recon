"""Daily break report: one Markdown page plus two charts, built only from the SQL views."""
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from . import config  # noqa: E402
from .db import read_df  # noqa: E402

SEVERITY_LABEL = {3: "High", 2: "Medium", 1: "Low"}
TYPE_LABEL = {
    "missing_at_broker": "Missing at broker",
    "missing_internally": "Missing internally",
    "quantity_mismatch": "Quantity mismatch",
    "price_mismatch": "Price mismatch",
    "side_mismatch": "Side mismatch",
    "duplicate": "Duplicate",
    "settlement_date_mismatch": "Settlement date mismatch",
}


def _table(df, headers):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if v is None else str(v) for v in row) + " |")
    return "\n".join(lines)


def _bar_chart(by_type, path, run_date):
    fig, ax = plt.subplots(figsize=(8, 3.6))
    labels = [TYPE_LABEL[t] for t in by_type["break_type"]][::-1]
    counts = list(by_type["open_count"])[::-1]
    ax.barh(labels, counts, color="#3b6ea5")
    for y, c in enumerate(counts):
        ax.text(c, y, f" {c}", va="center", fontsize=9)
    ax.set_title(f"Open breaks by type, {run_date}", loc="left", fontsize=11)
    ax.spines[["top", "right"]].set_visible(False)
    ax.set_xlabel("open breaks")
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def _trend_chart(summary, path):
    fig, ax = plt.subplots(figsize=(8, 3.2))
    ax.plot(summary["run_date"], summary["match_rate_pct"], marker="o", ms=3,
            label="matched (any method)", color="#3b6ea5")
    ax.plot(summary["run_date"], summary["clean_match_rate_pct"], marker="o", ms=3,
            label="matched with no differences", color="#c0703a")
    ax.set_title("Match rate over the period", loc="left", fontsize=11)
    ax.set_ylabel("% of trades compared")
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False, fontsize=8, loc="lower left")
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def build_report(conn, run_date=None):
    summary = read_df(conn, "SELECT * FROM v_daily_summary ORDER BY run_date")
    if summary.empty:
        raise SystemExit("No reconciliation runs found. Run `python -m recon run` first.")
    if run_date is None:
        run_date = summary["run_date"].iloc[-1]
    head = summary[summary["run_date"] == run_date]
    if head.empty:
        raise SystemExit(f"No run for {run_date}.")
    h = head.iloc[0]

    by_type = read_df(conn, "SELECT break_type, open_count, share_pct FROM v_breaks_by_type "
                            "WHERE run_date = %s ORDER BY sort_order", (run_date,))
    top = read_df(conn, """
        SELECT rank, severity, break_type, trade_id, broker_ref, detail, age_days, suggested_owner
          FROM v_top_breaks WHERE run_date = %s AND rank <= 10 ORDER BY rank""", (run_date,))
    ageing = read_df(conn, "SELECT bucket, open_count FROM v_ageing WHERE run_date = %s "
                           "ORDER BY sort_order", (run_date,))
    health = read_df(conn, "SELECT * FROM v_matcher_health WHERE run_date = %s", (run_date,)).iloc[0]

    config.REPORTS_DIR.mkdir(exist_ok=True)
    bar = f"breaks_by_type_{run_date}.png"
    trend = "match_rate_trend.png"
    _bar_chart(by_type, config.REPORTS_DIR / bar, run_date)
    _trend_chart(summary, config.REPORTS_DIR / trend)

    change = h["change_vs_prev"]
    change_txt = "first run" if change is None or change != change else f"{int(change):+d} vs previous run"
    total_matched = int(health["exact_matches"] + health["fuzzy_matches"] + health["partial_matches"])

    by_type_tbl = by_type.assign(
        break_type=by_type["break_type"].map(TYPE_LABEL),
        share_pct=by_type["share_pct"].map(lambda v: "0.0%" if v != v or v is None else f"{v:.1f}%"))
    top_tbl = top.assign(
        severity=top["severity"].map(SEVERITY_LABEL),
        break_type=top["break_type"].map(TYPE_LABEL),
        trade_id=top["trade_id"].fillna("-"),
        broker_ref=top["broker_ref"].fillna("-"))

    md = f"""# Daily break report - {run_date}

> Synthetic data. Every trade in this report was generated by the tool; none of it is real.

## Headline

| Trades compared | Match rate | Clean match rate | Open breaks | Change | New today | Resolved today |
|---|---|---|---|---|---|---|
| {int(h['trades_compared']):,} | {h['match_rate_pct']:.2f}% | {h['clean_match_rate_pct']:.2f}% | {int(h['open_breaks'])} | {change_txt} | {int(h['new_breaks'])} | {int(h['resolved_breaks'])} |

*Match rate* = internal trades paired with a broker record by any pass.
*Clean match rate* = paired and every compared field agrees.

## Breaks by type

{_table(by_type_tbl, ["Break type", "Open", "Share"])}

![Open breaks by type]({bar})

## Top 10 breaks (severity, then age, then notional)

{_table(top_tbl, ["#", "Severity", "Type", "Trade ID", "Broker ref", "What differs", "Age (bus. days)", "Owner"])}

## Ageing of open breaks

{_table(ageing, ["Age", "Open breaks"])}

## Matcher health

| Exact (trade_id) | Fuzzy (economics) | Partial (one field off) | Total matched | Unmatched internal | Unmatched broker | Duplicates flagged |
|---|---|---|---|---|---|---|
| {int(health['exact_matches']):,} | {int(health['fuzzy_matches'])} | {int(health['partial_matches'])} | {total_matched:,} | {int(health['unmatched_internal'])} | {int(health['unmatched_broker'])} | {int(health['duplicates_flagged'])} |

{health['fallback_share_pct']:.2f}% of matches needed a fallback pass because the broker's trade_id was blank or wrong.

## Match rate over the period

![Match rate trend]({trend})
"""
    path = config.REPORTS_DIR / f"break_report_{run_date}.md"
    path.write_text(md, encoding="utf-8")
    return path
